const os=require('node:os'),path=require('node:path'),fs=require('node:fs')
const { initializeApp, cert } = require('firebase-admin/app')
const { getFirestore } = require('firebase-admin/firestore')
const kf=process.env.GOOGLE_APPLICATION_CREDENTIALS||path.join(os.homedir(),'ekhaya-keys','firebase-sa.json')
initializeApp({credential:cert(JSON.parse(fs.readFileSync(kf,'utf8')))})
const db=getFirestore()
const note=t=>console.log(process.env.GITHUB_ACTIONS?`::notice::${t}`:t)
;(async()=>{
  const snap=await db.collection('fixtures').get()
  const rows=snap.docs.map(d=>({id:d.id,...d.data()})).filter(f=>!f.isTest)
  const nonFinished=rows.filter(f=>f.status!=='finished').sort((a,b)=>String(a.date).localeCompare(String(b.date)))
  note(`fixtures: ${rows.length} total; ${nonFinished.length} not finished`)
  for(const f of nonFinished) note(`  [${f.squad??'men'}] ${f.status} · ${f.date} · ${f.home} v ${f.away}`)
})().catch(e=>{console.log('::error::'+e.message);process.exit(1)})
